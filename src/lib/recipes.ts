/** 냉장고 털기에서 고를 재료 (레시피 재료를 다 모으되 기본양념은 뺀다) */
export const PANTRY: string[] = [...new Set(RECIPES.flatMap((x) => x.ingredients))].filter((i) => !BASICS.includes(i))

/** 기본양념 말고 필요한 재료가 다 있는 레시피만, 걸리는 시간 짧은 순 */
export function recipesWith(have: string[], all: Recipe[] = RECIPES): Recipe[] {
  const got = new Set(have)
  return all
    .filter((x) => x.ingredients.every((i) => BASICS.includes(i) || got.has(i)))
    .sort((a, b) => a.minutes - b.minutes)
}

/** 레시피 태그 목록 (거르기 칩) */
export const RECIPE_TAGS: string[] = [...new Set(RECIPES.flatMap((x) => x.tags))]
